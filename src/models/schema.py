"""
Pydantic Schemas for the Scholarship Intelligence System.
Implements the Universal Normalized Schema matching Atlas Funding expectations,
complete with field-level evidence grounding, anti-hallucination guards, and change auditing.
"""

from typing import List, Optional, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field, HttpUrl, field_validator
from src.models.enums import ScholarshipStatus, VerificationStatus, ProviderType, GenderCriteria


class EvidenceItem(BaseModel):
    """
    Field-level evidence link proving the authenticity of an extracted field value.
    Provides complete auditability: Database -> Source URL -> Evidence Snippet -> Extracted Value.
    """
    field_name: str = Field(..., description="Name of the extracted scholarship field")
    extracted_value: str = Field(..., description="Normalized value stored in database")
    source_url: str = Field(..., description="Official URL from which evidence was parsed")
    evidence_text: str = Field(..., description="Verbatim text quote from source document / DOM")
    match_score: float = Field(default=100.0, description="Confidence percentage for this specific snippet (0-100)")
    verified_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())


class ChangeLogRecord(BaseModel):
    """
    Audit record tracking historical changes between crawl runs.
    Ensures updates never silently overwrite previous values.
    """
    scholarship_id: str
    field_name: str
    old_value: str
    new_value: str
    detected_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    source_url: str
    evidence_text: str
    run_id: str


class ConfidenceScorecard(BaseModel):
    """
    Explainable, mathematical 100-point confidence scorecard.
    Strictly generated by deterministic verification algorithms, not arbitrary LLM guessing.
    """
    domain_score: float = Field(..., description="Domain authenticity (0 to 25)")
    reachability_score: float = Field(..., description="HTTP 200 & SSL reachability (0 to 15)")
    evidence_score: float = Field(..., description="Direct DOM evidence match for core criteria (0 to 25)")
    app_url_score: float = Field(..., description="Valid official application pathway (0 to 10)")
    temporal_score: float = Field(..., description="Currency and deadline validation (0 to 15)")
    consistency_score: float = Field(..., description="Absence of contradictions (0 to 10)")
    total_score: float = Field(..., description="Overall confidence percentage (0 to 100)")
    verification_status: VerificationStatus
    reasons: List[str] = Field(default_factory=list, description="Line-item justification for 'Why this score?'")


class ScholarshipRecord(BaseModel):
    """
    Universal Normalized Scholarship Record.
    Implements 18+ high-fidelity fields required for comprehensive student matching.
    """
    id: str = Field(..., description="Unique alphanumeric slug identifier")
    scholarship_name: str = Field(..., description="Official title of the scholarship scheme")
    provider: str = Field(..., description="Awarding organization, ministry, or corporate body")
    provider_type: ProviderType = Field(..., description="Category: Govt, CSR, Trust, University")
    
    # Official Source & Links
    official_source_url: str = Field(..., description="Primary authoritative source page URL")
    application_url: str = Field(default="Not specified", description="Direct official application or registration portal")
    
    # Benefits & Financials
    amount_benefit: str = Field(..., description="Detailed textual description of financial grant and perks")
    amount_value_inr: Optional[float] = Field(default=None, description="Normalized annual monetary benefit in INR for filtering")
    
    # Eligibility Dimensions
    academic_requirements: str = Field(..., description="Minimum grades, eligible courses, qualifying exams")
    course_level: List[str] = Field(default_factory=list, description="Target levels: UG, PG, PhD, School")
    income_criteria: str = Field(default="Not specified", description="Family income threshold e.g. ≤ ₹2,50,000 or Not specified")
    income_limit_inr: Optional[float] = Field(default=None, description="Normalized numeric family income ceiling in INR")
    age_criteria: str = Field(default="Not specified", description="Age restriction or Not specified")
    gender_criteria: str = Field(default="All", description="All, Female Only, etc.")
    category_criteria: str = Field(default="All / General", description="SC, ST, OBC, EWS, Minority, PwD, etc.")
    domicile_state: str = Field(default="All India", description="State requirement or All India")
    institution_requirements: str = Field(default="Any recognized institution", description="Eligible universities/colleges")
    
    # Operational Dates & Procedures
    opening_date: str = Field(default="Not specified", description="Application open date (YYYY-MM-DD or Not specified)")
    closing_date: str = Field(..., description="Application closing deadline (YYYY-MM-DD or Rolling / Not specified)")
    documents_required: List[str] = Field(default_factory=list, description="List of required verification documents")
    selection_process: str = Field(default="Merit-cum-Means evaluation", description="Selection procedure")
    renewal_requirements: str = Field(default="Not specified", description="Conditions for continuing support in subsequent years")
    
    # Verification & Status
    status: ScholarshipStatus = Field(default=ScholarshipStatus.ACTIVE)
    confidence_score: float = Field(..., ge=0.0, le=100.0, description="Deterministic confidence score (0-100%)")
    verification_status: VerificationStatus = Field(..., description="VERIFIED (>=95%) or REVIEW REQUIRED")
    score_breakdown: Optional[ConfidenceScorecard] = Field(default=None)
    last_verified_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    
    # Grounded Evidence & Audit Trail
    evidence_items: List[EvidenceItem] = Field(default_factory=list, description="Audit trail of exact textual proof")

    @field_validator("confidence_score")
    @classmethod
    def validate_confidence_range(cls, v: float) -> float:
        return round(float(v), 2)


class CrawlRunRecord(BaseModel):
    """
    Tracks metadata and operational logs for continuous crawler runs.
    """
    run_id: str
    run_type: str = "SCHEDULED_CRAWL"  # BASE_CRAWL, RE_CRAWL, SCHEDULED_CRAWL
    started_at: str
    completed_at: Optional[str] = None
    total_discovered: int = 0
    total_verified: int = 0
    total_review_required: int = 0
    total_changes_detected: int = 0
    total_expired_detected: int = 0
    log_summary: str = ""
